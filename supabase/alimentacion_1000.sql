create extension if not exists pgcrypto;

create table if not exists food_reference (
 id uuid primary key default gen_random_uuid(),
 name text not null, category text not null, portion_label text not null,
 portion_grams numeric not null check(portion_grams>0),
 kcal_per_100g numeric not null check(kcal_per_100g>=0),
 kcal_per_portion numeric not null check(kcal_per_portion>=0),
 source text not null default 'estimado',
 unique(name,portion_label)
);
alter table food_reference enable row level security;
drop policy if exists "authenticated can read food reference" on food_reference;
create policy "authenticated can read food reference" on food_reference for select to authenticated using (true);

alter table meals add column if not exists description text;
alter table meals add column if not exists meal_type text default 'Comida';
alter table meals add column if not exists entry_mode text default 'catalogo';
alter table meals add column if not exists portion_label text;
alter table meals add column if not exists quantity numeric default 1;
alter table meals alter column grams drop not null;

